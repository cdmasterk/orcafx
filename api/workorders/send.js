// api/workorders/send.js
import fs from "fs";
import path from "path";
import { PDFDocument, rgb } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import czsClient from "../../src/lib/czsClient.js";

const BREVO_API_KEY = process.env.BREVO_API_KEY;

export default async function handler(req, res) {
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  try {
    const { workOrderId, emailToSend } = req.body || {};
    if (!workOrderId || !emailToSend) {
      return res.status(400).json({ error: "Missing parameters: workOrderId, emailToSend" });
    }

    // 1️⃣ Dohvati work order iz Supabase-a
    const { data: wo, error } = await czsClient.from("work_orders").select("*").eq("id", workOrderId).single();
    if (error || !wo) throw new Error("Work order not found");

    // 2️⃣ Kreiraj PDF
    const pdfDoc = await PDFDocument.create();
    pdfDoc.registerFontkit(fontkit);

    const fontPath = path.resolve("./public/fonts/DejaVuSans.ttf");
    const fontBytes = fs.readFileSync(fontPath);
    const font = await pdfDoc.embedFont(fontBytes);

    const page = pdfDoc.addPage([595.28, 841.89]);
    const { width } = page.getSize();
    let y = 800;

    const draw = (label, val) => {
      page.drawText(`${label}:`, { x: 40, y, size: 12, font, color: rgb(0, 0, 0) });
      page.drawText(String(val || "-"), { x: 150, y, size: 12, font, color: rgb(0, 0, 0) });
      y -= 18;
    };

    page.drawText("RADNI NALOG / WORK ORDER", { x: 40, y, size: 16, font, color: rgb(0.1, 0.1, 0.1) });
    y -= 25;
    draw("Order No", wo.order_no);
    draw("Customer", wo.customer_name);
    draw("Email", emailToSend);
    draw("Purity", wo.purity);
    draw("Color", wo.color);
    draw("Quantity", wo.quantity);
    draw("Status", wo.status);
    draw("Date", new Date().toLocaleString());
    y -= 20;
    page.drawText("Generated by ORCA System", { x: 40, y, size: 10, font, color: rgb(0.4, 0.4, 0.4) });

    const pdfBytes = await pdfDoc.save();
    const pdfBase64 = Buffer.from(pdfBytes).toString("base64");

    // 3️⃣ Pošalji e-mail putem Brevo API
    const payload = {
      sender: { name: "ORCA Production", email: "noreply@orca.hr" },
      to: [{ email: emailToSend }],
      subject: `Radni nalog ${wo.order_no}`,
      htmlContent: `<p>Poštovani,</p><p>U privitku se nalazi radni nalog <b>${wo.order_no}</b>.</p><p>Srdačan pozdrav,<br/>ORCA Team</p>`,
      attachment: [{ name: `${wo.order_no}.pdf`, content: pdfBase64 }],
    };

    const response = await fetch("https://api.brevo.com/v3/smtp/email", {
      method: "POST",
      headers: { "Content-Type": "application/json", "api-key": BREVO_API_KEY },
      body: JSON.stringify(payload),
    });

    if (!response.ok) {
      const txt = await response.text();
      throw new Error(`Brevo send failed: ${txt}`);
    }

    // 4️⃣ Log u bazu
    const entry = {
      time: new Date().toISOString(),
      recipient: emailToSend,
      order_no: wo.order_no,
    };

    await czsClient.from("work_orders").update({ email_log: [...(wo.email_log || []), entry] }).eq("id", wo.id);

    return res.status(200).json({ ok: true, mailed: true, pdfBase64, order_no: wo.order_no });
  } catch (err) {
    console.error("❌ send.js error:", err);
    return res.status(500).json({ mailed: false, error: err.message });
  }
}
