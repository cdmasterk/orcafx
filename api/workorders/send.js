// /api/workorders/send.js
import { createClient } from "@supabase/supabase-js";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";

// VERCEL ENV
const SUPABASE_URL = process.env.SUPABASE_URL;
const SUPABASE_SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY; // server-side key
const BREVO_API_KEY = process.env.BREVO_API_KEY;
const APP_BASE_URL = process.env.APP_BASE_URL || "https://yourapp.example.com";
const INTERNAL_PRODUCTION_EMAILS = (process.env.INTERNAL_PRODUCTION_EMAILS || "")
  .split(",")
  .map((s) => s.trim())
  .filter(Boolean);

const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);

// ---- helpers ----
async function fetchWorkOrderById(workOrderId) {
  const { data, error } = await supabase
    .from("work_orders")
    .select(`*,
      partners:partner_id ( partner_name, emails, type )
    `)
    .eq("id", workOrderId)
    .single();
  if (error || !data) throw new Error("Work order not found");
  return data;
}

async function fetchWorkOrderByCustomOrder(orderId) {
  const { data, error } = await supabase
    .from("work_orders")
    .select(`*,
      partners:partner_id ( partner_name, emails, type )
    `)
    .eq("source_order_id", orderId)
    .order("created_at", { ascending: false })
    .limit(1)
    .single();
  if (error || !data) throw new Error("Work order not found for provided Custom Order ID");
  return data;
}

async function buildPdf(wo) {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([595.28, 841.89]); // A4
  const { width } = page.getSize();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  // Header
  page.drawText("WORK ORDER / RADNI NALOG", {
    x: 40,
    y: 800,
    size: 16,
    font: fontBold,
    color: rgb(0.05, 0.05, 0.05),
  });
  page.drawText(`No: ${wo.order_no ?? "N/A"}`, { x: 40, y: 780, size: 12, font });
  page.drawText(`Date: ${new Date().toLocaleDateString()}`, {
    x: width - 200,
    y: 780,
    size: 12,
    font,
  });

  // Details
  let y = 750;
  const lineGap = 18;
  const draw = (label, val) => {
    page.drawText(label, { x: 40, y, size: 11, font: fontBold });
    page.drawText(val || "-", { x: 180, y, size: 11, font });
    y -= lineGap;
  };
  draw("Customer:", wo.customer_name ?? "N/A");
  draw("Product Type:", wo.product_type ?? "N/A");
  draw("Purity:", wo.purity ?? "N/A");
  draw("Color:", wo.color ?? "N/A");
  draw("Quantity:", String(wo.quantity ?? 1));
  draw("Status:", wo.status ?? "PENDING");
  draw("Partner:", wo.partners?.partner_name ?? "—");

  // Description
  page.drawText("Description:", { x: 40, y, size: 11, font: fontBold });
  const desc = wo.description ?? "N/A";
  y -= lineGap;
  const wrap = (text, maxChars = 90) =>
    text ? text.match(new RegExp(`.{1,${maxChars}}`, "g")) || [text] : [""];
  for (const line of wrap(desc)) {
    page.drawText(line, { x: 60, y, size: 11, font });
    y -= 14;
  }
  y -= 10;

  // QR (link to public order page)
  const publicUrl = `${APP_BASE_URL}/orders/actions/${wo.id}`;
  const qrUrl = `https://api.qrserver.com/v1/create-qr-code/?size=220x220&data=${encodeURIComponent(
    publicUrl
  )}`;
  const qrRes = await fetch(qrUrl);
  if (qrRes.ok) {
    const pngBytes = new Uint8Array(await qrRes.arrayBuffer());
    const qrImage = await pdfDoc.embedPng(pngBytes);
    const qrSize = 120;
    page.drawImage(qrImage, { x: width - qrSize - 40, y: 650, width: qrSize, height: qrSize });
    page.drawText("Scan for digital view", {
      x: width - qrSize - 40,
      y: 640,
      size: 9,
      font,
      color: rgb(0.3, 0.3, 0.3),
    });
  }

  // Signature & footer
  page.drawText("Workshop signature / Potpis radionice:", {
    x: 40,
    y: 180,
    size: 11,
    font: fontBold,
  });
  page.drawLine({
    start: { x: 40, y: 170 },
    end: { x: width - 40, y: 170 },
    thickness: 0.5,
    color: rgb(0.7, 0.7, 0.7),
  });
  page.drawText("Generated by ORCA Production System", {
    x: 40,
    y: 60,
    size: 9,
    font,
    color: rgb(0.5, 0.5, 0.5),
  });

  return await pdfDoc.save();
}

async function sendBrevo({ toList, subject, htmlContent, pdfBytes, filename }) {
  const payload = {
    sender: { name: "Zlatarna Križek", email: "noreply@krizek.hr" },
    to: toList.map((email) => ({ email })),
    subject,
    htmlContent,
    textContent: "",
    attachment: [
      { name: filename, content: Buffer.from(pdfBytes).toString("base64") },
    ],
  };

  const resp = await fetch("https://api.brevo.com/v3/smtp/email", {
    method: "POST",
    headers: {
      accept: "application/json",
      "api-key": BREVO_API_KEY,
      "content-type": "application/json",
    },
    body: JSON.stringify(payload),
  });

  if (!resp.ok) {
    const t = await resp.text().catch(() => "");
    throw new Error(`Brevo send error: ${resp.status} ${t}`);
  }
  return true;
}

// ---- handler ----
export default async function handler(req, res) {
  if (req.method !== "POST")
    return res.status(405).json({ error: "Method not allowed" });

  try {
    const { workOrderId, orderId } = req.body || {};
    if (!workOrderId && !orderId) {
      return res
        .status(400)
        .json({ error: "workOrderId or orderId is required" });
    }

    // Get work order
    const wo = workOrderId
      ? await fetchWorkOrderById(workOrderId)
      : await fetchWorkOrderByCustomOrder(orderId);

    // Build recipient list
    const partnerEmails = Array.isArray(wo?.partners?.emails)
      ? wo.partners.emails
      : [];
    const customer = wo.customer_email ? [wo.customer_email] : [];
    const toList = [...new Set([...partnerEmails, ...INTERNAL_PRODUCTION_EMAILS, ...customer])];

    // Build PDF
    const pdfBytes = await buildPdf(wo);
    const filename = `${wo.order_no || wo.id}.pdf`;

    // If no recipients, return pdf so frontend može manualno preuzeti
    if (toList.length === 0) {
      return res.status(200).json({
        ok: true,
        mailed: { sent: false, reason: "no recipients", toList },
        order_no: wo.order_no,
        workOrderId: wo.id,
        pdfBase64: Buffer.from(pdfBytes).toString("base64"),
      });
    }

    // Send email via Brevo
    const subject = `Work Order ${wo.order_no ?? wo.id}`;
    const htmlContent = `
      <p>Poštovani,</p>
      <p>U privitku se nalazi radni nalog <b>${wo.order_no ?? wo.id}</b>.</p>
      <p>Srdačan pozdrav,<br/>ORCA Production System</p>
    `;
    await sendBrevo({ toList, subject, htmlContent, pdfBytes, filename });

    // Log in DB
    const entry = { time: new Date().toISOString(), result: { sent: true, toList } };
    const current = Array.isArray(wo.email_log) ? wo.email_log : [];
    await supabase.from("work_orders").update({ email_log: [...current, entry] }).eq("id", wo.id);

    return res.status(200).json({
      ok: true,
      mailed: { sent: true, toList },
      order_no: wo.order_no,
      workOrderId: wo.id,
      pdfBase64: Buffer.from(pdfBytes).toString("base64"),
    });
  } catch (err) {
    console.error("❌ WorkOrder send error:", err);
    return res.status(500).json({ error: String(err.message || err) });
  }
}
