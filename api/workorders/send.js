import fs from "fs";
import path from "path";
import { PDFDocument, rgb, StandardFonts } from "pdf-lib";
import fontkit from "@pdf-lib/fontkit";
import { createClient } from "@supabase/supabase-js";

// 🔑 ENVIRONMENT
const SUPABASE_URL = process.env.SUPABASE_URL;
const SUPABASE_SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const BREVO_API_KEY = process.env.BREVO_API_KEY;

const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY);

// 📄 FONT PATHS
const FONTS_DIR = path.join(process.cwd(), "public", "fonts");
const FONT_PRIMARY = path.join(FONTS_DIR, "NotoSans-Regular.ttf");
const FONT_FALLBACK = path.join(FONTS_DIR, "DejaVuSans.ttf");

// ---------- PDF BUILDER ----------
async function buildPdf(order, company) {
  const pdfDoc = await PDFDocument.create();
  pdfDoc.registerFontkit(fontkit);

  let fontBytes = null;
  let usedFontName = "";

  try {
    if (fs.existsSync(FONT_PRIMARY)) {
      fontBytes = fs.readFileSync(FONT_PRIMARY);
      usedFontName = "NotoSans-Regular.ttf";
    } else if (fs.existsSync(FONT_FALLBACK)) {
      fontBytes = fs.readFileSync(FONT_FALLBACK);
      usedFontName = "DejaVuSans.ttf";
    }
  } catch {}

  if (!fontBytes) {
    throw new Error(
      "Unicode font not found. Add NotoSans-Regular.ttf or DejaVuSans.ttf to /public/fonts/"
    );
  }

  const font = await pdfDoc.embedFont(fontBytes);
  const page = pdfDoc.addPage([595, 842]);
  const { width, height } = page.getSize();

  const draw = (text, x, y, size = 11) =>
    page.drawText(String(text ?? "-"), { x, y, size, font, color: rgb(0, 0, 0) });

  // 🏢 HEADER
  const companyName = company?.legal_name || "Zlatarna Krizek doo";
  const address = [company?.address_line, company?.city, company?.country].filter(Boolean).join(", ");
  let y = height - 40;

  draw(companyName, 40, y, 16);
  draw(address, 40, y - 18, 10);
  const contact = [company?.email, company?.phone, company?.tax_id ? `OIB: ${company.tax_id}` : ""]
    .filter(Boolean)
    .join(" | ");
  draw(contact, 40, y - 32, 10);

  y -= 60;
  page.drawLine({ start: { x: 40, y }, end: { x: width - 40, y }, thickness: 1, color: rgb(0.1, 0.1, 0.1) });
  y -= 30;

  draw(`RADNI NALOG ${order.order_no ?? ""}`, 40, y, 18);
  y -= 22;
  draw(`Datum narudžbe: ${formatDate(order.order_date)}`, 40, y);
  draw(`Rok izrade: ${formatDate(order.due_date)}`, 300, y);
  y -= 24;

  // helper section
  const section = (title) => {
    y -= 12;
    page.drawLine({ start: { x: 40, y }, end: { x: width - 40, y }, thickness: 0.5, color: rgb(0.5, 0.5, 0.5) });
    y -= 20;
    draw(title, 40, y, 13);
    y -= 18;
  };

  // 👤 CUSTOMER
  section("KUPAC");
  draw(`Ime: ${order.customer_name ?? "-"}`, 60, y); y -= 18;
  draw(`Email: ${order.customer_email ?? "-"}`, 60, y); y -= 18;
  draw(`Telefon: ${order.customer_phone ?? "-"}`, 60, y); y -= 6;

  // 📦 SPECIFIKACIJE
  section("SPECIFIKACIJE");
  const specs = [
    ["Kategorija", order.category],
    ["Model", order.model],
    ["Čistoća", order.purity],
    ["Boja", order.color],
    ["Količina", order.quantity],
    ["Status", order.status],
  ];
  for (const [k, v] of specs) { draw(`${k}: ${v ?? "-"}`, 60, y); y -= 18; }
  y -= 6;

  // 💍 DETALJI
  section("DETALJI");
  const details = [
    ["Veličina (muška)", order.male_size],
    ["Veličina (ženska)", order.female_size],
    ["Kamenje", order.stones],
    ["Gravura 1", order.engraving_1],
    ["Gravura 2", order.engraving_2],
    ["Zajednička gravura", order.joint_engraving],
  ];
  for (const [k, v] of details) { draw(`${k}: ${v ?? "-"}`, 60, y); y -= 18; }

  // 💬 NAPOMENE
  section("DODATNE NAPOMENE");
  multiLine(page, font, order.additional_comment ?? "-", 60, y, 11, 460, 16);
  y -= 100;

  // 🖼️ SKICA
  if (order.sketch_url) {
    section("SKICA");
    try {
      const buf = await fetch(order.sketch_url).then((r) => r.arrayBuffer());
      let img;
      try { img = await pdfDoc.embedPng(buf); } catch { img = await pdfDoc.embedJpg(buf); }
      const W = 180, H = 180;
      page.drawImage(img, { x: 60, y: y - H, width: W, height: H });
      y -= H + 20;
    } catch {
      draw("⚠️ Skica nije učitana", 60, y); y -= 18;
    }
  }

  // 🧩 QR CODE (bez dodatnih paketa; preuzima PNG sa servisa)
  try {
    const qrUrlValue = `https://orcafx.vercel.app/orders/${encodeURIComponent(order.order_no)}`;
    const qrPngUrl = `https://api.qrserver.com/v1/create-qr-code/?size=140x140&margin=0&data=${encodeURIComponent(qrUrlValue)}`;
    const qrBuf = await fetch(qrPngUrl).then((r) => r.arrayBuffer());
    const qrImg = await pdfDoc.embedPng(qrBuf);
    page.drawImage(qrImg, { x: width - 130, y: 50, width: 90, height: 90 });
    draw("QR → digitalni nalog", width - 160, 40, 8);
  } catch {
    // tiho preskoči QR ako vanjski servis nije dostupan
  }

  // FOOTER
  draw(`Generated by ORCAFX • Font: ${usedFontName} • ${new Date().toLocaleString("hr-HR")}`, 40, 40, 9);

  const bytes = await pdfDoc.save();
  return Buffer.from(bytes).toString("base64");
}

// ---------- UTILS ----------
function formatDate(v) {
  if (!v) return "-";
  try { return new Date(v).toLocaleString("hr-HR"); } catch { return String(v); }
}
function multiLine(page, font, text, x, y, size, maxWidth, leading) {
  const words = String(text || "-").split(/\s+/);
  let line = "";
  for (const w of words) {
    const test = line ? `${line} ${w}` : w;
    const wpx = font.widthOfTextAtSize(test, size);
    if (wpx > maxWidth) { page.drawText(line, { x, y, size, font }); y -= leading; line = w; }
    else { line = test; }
  }
  if (line) page.drawText(line, { x, y, size, font });
}

// ---------- EMAIL SENDER ----------
async function sendEmail(to, pdfBase64, order_no) {
  const payload = {
    sender: { name: "Zlatarna Krizek", email: "noreply@krizek.hr" },
    to: [{ email: to }],
    subject: `Radni nalog ${order_no}`,
    htmlContent: `<p>Poštovani,</p><p>U privitku se nalazi radni nalog <b>${order_no}</b>.</p><p>Lijep pozdrav,<br>Zlatarna Križek</p>`,
    attachment: [{ name: `${order_no}.pdf`, base64Content: pdfBase64 }],
  };
  const res = await fetch("https://api.brevo.com/v3/smtp/email", {
    method: "POST",
    headers: { accept: "application/json", "content-type": "application/json", "api-key": BREVO_API_KEY },
    body: JSON.stringify(payload),
  });
  const txt = await res.text();
  if (!res.ok) throw new Error(`Brevo error: ${txt}`);
  return JSON.parse(txt);
}

// ---------- HANDLER ----------
export default async function handler(req, res) {
  if (req.method !== "POST") return res.status(405).json({ error: "Method not allowed" });

  const { workOrderId, emailToSend } = req.body || {};
  if (!workOrderId || !emailToSend)
    return res.status(400).json({ ok: false, error: "Missing parameters: workOrderId, emailToSend" });

  try {
    // 1) Work order
    const { data: order, error: woErr } = await supabase
      .from("work_orders")
      .select("*")
      .eq("id", workOrderId)
      .single();
    if (woErr || !order) throw new Error("Work order not found");

    // 2) Custom order join (ako postoji)
    let custom = {};
    if (order.custom_order_id) {
      const { data: c, error: cErr } = await supabase
        .from("custom_orders")
        .select(
          "category, model, male_size, female_size, stones, engraving_1, engraving_2, joint_engraving, additional_comment, sketch_url"
        )
        .eq("id", order.custom_order_id)
        .single();
      if (!cErr && c) custom = c;
    }

    // 3) Company profile
    const { data: company } = await supabase
      .from("company_profile")
      .select("legal_name, address_line, city, country, email, phone, tax_id, logo_url")
      .limit(1)
      .single();

    // Merge
    const mergedOrder = { ...order, ...custom };

    // 4) Build PDF
    const pdfBase64 = await buildPdf(mergedOrder, company);

    // 5) Print-only
    if (emailToSend === "printonly@local")
      return res.status(200).json({ ok: true, pdfBase64, order_no: order.order_no });

    // 6) Send mail
    const result = await sendEmail(emailToSend, pdfBase64, order.order_no);

    // 7) Log success
    await supabase.rpc("fn_wo_log_email", {
      p_work_order_id: workOrderId,
      p_to: emailToSend,
      p_status: "SENT",
      p_provider_id: result?.messageId ?? null,
      p_error: null,
      p_payload: result ?? {},
    });

    return res.status(200).json({ ok: true, result });
  } catch (e) {
    console.error("❌ send.js error:", e.message);
    try {
      await supabase.rpc("fn_wo_log_email", {
        p_work_order_id: req.body?.workOrderId ?? null,
        p_to: req.body?.emailToSend ?? null,
        p_status: "FAILED",
        p_provider_id: null,
        p_error: e.message?.slice(0, 300) || "unknown",
        p_payload: {},
      });
    } catch {}
    return res.status(500).json({ ok: false, error: e.message });
  }
}
